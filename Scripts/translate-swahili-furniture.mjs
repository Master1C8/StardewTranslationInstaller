function translate(value) {
  if (exact.has(value)) return exact.get(value);
  for (const [suffix, [noun, connector]] of nouns) {
    if (value === suffix) return noun;
    if (!value.endsWith(` ${suffix}`)) continue;
    const modifier = value.slice(0, -(suffix.length + 1));
    const translatedModifier = modifiers.get(modifier);
    if (translatedModifier !== undefined) return `${noun} ${connector} ${translatedModifier}`;
  }
  return null;
}

const unresolved = [];
let changed = 0;
for (const [key, original] of Object.entries(source)) {
  if (entries[key] !== original) continue;
  const translated = translate(original);
  if ((!translated || translated === original) && intentionallyUnchangedKeys.has(key)) continue;
  if (!translated || translated === original) unresolved.push([key, original]);
  else {
    entries[key] = translated;
    changed += 1;
  }
}

